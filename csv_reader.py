# Define a custom row class to store the CSV per row data vs using standard containers directly

class csvRow():
    def __init__(self):
        self.source = ""            # the raw text data defining this instance
        self.row_num = -1       # its original line number in file
        self.header = ""            # reference to the file's header text
        self.vals = []
        self.primary_index = -1     # There is a primary field (ID) for the data, often in position [0]
        self.secondary_index = -1   # The task's major magnet field, but secondary to ID
        self.fields  = {}             # optional dict for accessing fields by key (string)

    # Using a slice defends this code from crashing on accessing an out of range index.
    #print provides only a limited view of the data set, for faster easier development.
    def __repr__(self):
        safe = self.secondary_index
        return f"csvRow: {self.row_num:3d}: {self.vals[safe: safe+1]} => {self.source}\n"
