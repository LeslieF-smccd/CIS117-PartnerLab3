    collect_rows = []
    header = None
    primary_index, secondary_index = -1, -1

    row_count = -1

    # Process each line-row and split by comma and save data into a 2D structure
    for row in csv_rows:
        # Remove \n character from the data, encountered by file open API
        row = row.strip("\n")
        row_count += 1

        precells = []
        dquote = '"'
