class csvDataBase():
    def __init__(self, source = ''):
        self.source = source           # the file (string) which defined the database location
        self.header = None              # reference to the file's header (first row) text fields
        self.raw_header = ""            # raw text of the file's header
        self.primary_index = -1       # There is a primary field (ID) for row data, often in position [0]
        self.secondary_index = -1    # The task's (minor) magnet for reporting processing field.
        self.primary_field = ''           # Lab 3 assignment expects ID as "name"
        self.secondary_field = ''        # Lab 3 assignment task expects grouping by "region"
        self.csv_store  = {}              # list of csvRow for database, in file's order (minus header)
        self.major_fields = {}          # List tree of minor key values which own major keys' values.
        self.minor_dict = {}            # A dict of all rows grouped by the minor key values.
        self.major_dict = {}

    # Generate a dict (to reuse) for searching DB for a field having specific field value,
    # singleton use. Thus any duplicates emit a warning, and only the last one gets saved/
    def getFieldCSVSingle(self, header_value):
        fly = {}
        if header_value in self.header:
            for csv in self.csv_store:
                fval = csv.fields[header_value]
                # print("Processing ", fval)
                if fval in fly:
                    print(f"Warning: duplicate entry found for for field '{header_value}'", csv)
                fly[fval] = csv
        return fly

    # Generate a dict (to reuse) for searching DB for a field having some specific field value
    # Multiple csvRow entries can be stored in the list for a client querying the dict.
    def getFieldCSVMulti(self, header_value):
        fly = {}
        if header_value in self.header:
            for csv in self.csv_store:
                fval = csv.fields[header_value]
                # print("Processing ", fval)
                if fval not in fly:
                    fly[fval] = [csv]
                else:
                    fly[fval].append(csv)
        return fly

    # Uses the getFieldCSVMulti method to store all primaries
    # and returns only one matching row (last one).
    def getMajorCSV(self, value):
        primary = self.primary_field
        if len(self.major_dict) == 0:
            upd = self.getFieldCSVMulti(primary)
            if len(upd) > 0:
                self.major_dict.update(upd)
        safe = self.major_dict.get(value, None)
        if safe == None or len(safe) < 1:
            return csvRow()
        return safe[-1]

    def __repr__(self):
        return f"csvDataBase for {self.source} holding\n{str(self.csv_store)}\n\
" + f"majors: {str(self.major_fields)}\nsecondary view: {str(self.minor_dict)}"


def _cleanQuotes(strq):
    dquote = '"'
    dlen = len(strq)
    if dlen < 2 or strq.find(dquote) < 0:
        return strq
    newstr = ""
    skip = 0
    for n in range(dlen - 1):
        if skip > 0:
            skip = 0
            continue
        char1, char2 = strq[n], strq[n+1]
        if char1 == char2 == dquote:
            newstr += char1
            skip = 1
            continue
        newstr += char1
    # Append the last character if it wasn't skipped
    if skip == 0 and dlen > 0:
        newstr += strq[-1]
    return newstr

