    # From the githubs main page at "https://github.com/LeslieF-smccd/url_data/blob/main/country_full.csv"

    key1 = main_field # "name"   # determines the primary_index
    key2 = group_field # "sub-region"  # determines the secondary_index
    paths = list(default_paths)
    datasource = ""
